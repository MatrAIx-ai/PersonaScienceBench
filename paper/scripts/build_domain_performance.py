"""Build the domain table from frozen available-endpoint task means (no model calls).

Inputs were exported from Experiment/02_performance_and_fields/data/all_available/
snapshot.json, averaging evaluable available trials within task. Saved domain
intervals are checked against data/performance_panel.csv. Avg. intervals use the
mean of four domain bootstrap draws, not the mean of their confidence bounds.
"""
from pathlib import Path
from collections import defaultdict
import csv, hashlib, json
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
B, SEED = 20000, 20261004
ARMS = ['persona_off', 'candidate_155', 'candidate_001', 'candidate_003', 'candidate_046']
DOMAINS = ['life', 'physical_engineering', 'math_cs', 'social_humanities']
NAMES = ['Life', 'Phys./Eng.', 'Math./CS', 'Soc./Hum.']
rows = list(csv.DictReader((ROOT/'data/domain_task_scores.csv').open()))
refs = {(r['group_id'], r['persona_id']): r for r in csv.DictReader((ROOT/'data/performance_panel.csv').open()) if r['level'] == 'super_family'}
# This snapshot has no study spanning domains: independent domain draws retain
# all within-study dependence. Fail rather than silently dropping covariance.
study_domains = defaultdict(set)
for r in rows:
    study_domains[r['source'], r['study_id']].add(r['domain'])
assert all(len(v) == 1 for v in study_domains.values())
values, output = {}, []
for arm in ARMS:
    domain_draws = []
    for domain in DOMAINS:
        sub = [r for r in rows if r['persona_id'] == arm and r['domain'] == domain]
        draws = np.zeros(B)
        for source in sorted({r['source'] for r in sub}):
            sr = [r for r in sub if r['source'] == source]
            clusters = tuple(sorted({r['study_id'] for r in sr}))
            sums = np.array([sum(float(r['score']) for r in sr if r['study_id'] == c) for c in clusters])
            counts = np.array([sum(r['study_id'] == c for r in sr) for c in clusters])
            seed = SEED + int(hashlib.sha256(json.dumps([source, clusters]).encode()).hexdigest()[:8], 16)
            weights = np.random.default_rng(seed).multinomial(len(clusters), np.full(len(clusters), 1/len(clusters)), size=B)
            draws += (weights @ sums)/(weights @ counts)*len(sr)/len(sub)
        mean = np.mean([float(r['score']) for r in sub])
        lo, hi = np.quantile(draws, [.025, .975])
        ref = refs[domain, arm]
        assert np.allclose([mean, lo, hi], [float(ref[k]) for k in ['mean', 'ci95_low', 'ci95_high']], atol=1e-9, rtol=0)
        values[domain, arm] = mean, lo, hi
        domain_draws.append(draws)
    values['average', arm] = (np.mean([values[d, arm][0] for d in DOMAINS]), *np.quantile(np.mean(domain_draws, axis=0), [.025, .975]))
for domain in [*DOMAINS, 'average']:
    for arm in ARMS:
        mean, lo, hi = values[domain, arm]
        output.append(dict(domain=domain, persona_id=arm, mean=mean, ci95_low=lo, ci95_high=hi))
with (ROOT/'data/domain_performance.csv').open('w', newline='') as f:
    w=csv.DictWriter(f, fieldnames=list(output[0])); w.writeheader(); w.writerows(output)

def cell(v):
    return r'\shortstack{' + f'{v[0]:.2f}' + r'\\{\fontsize{6}{7}\selectfont [' + f'{v[1]:.2f}, {v[2]:.2f}' + r']}}'
header = r'''% Generated by scripts/build_domain_performance.py from frozen available task means.
\centering
\captionsetup{hypcap=false,font={footnotesize,it}}
\begingroup
\scriptsize\setstretch{1.0}
\setlength{\tabcolsep}{1pt}
\renewcommand{\arraystretch}{1.5}
\begin{tabular*}{\linewidth}{@{\extracolsep{\fill}}lccccc@{}}
\toprule
Domain & Off & 155 & 001 & 003 & 046 \\
\midrule
'''
lines=[]
for domain,name in zip(DOMAINS,NAMES):
    lines.append(name+' & '+' & '.join(cell(values[domain,a]) for a in ARMS)+r' \\')
lines += [r'\midrule',r'\textbf{Avg.} & '+' & '.join(cell(values['average',a]) for a in ARMS)+r' \\']
footer = r'''
\bottomrule
\end{tabular*}
\par\smallskip\footnotesize\raggedright
\textit{Domains:} Life sciences; physical sciences and engineering;
mathematics and computer science; social sciences and humanities.\par
\endgroup
\captionof{table}{\textbf{Performance by scientific domain.} Mean normalized
score (0--100), with pointwise 95\% confidence intervals below.
Columns identify simulator personas; Avg. weights domains equally.}
\label{tab:performance-panel}
'''
(ROOT/'tables/performance_panel.tex').write_text(header+'\n'.join(lines)+footer)
print('Verified all 20 saved domain means and intervals; generated five Avg. intervals.')
