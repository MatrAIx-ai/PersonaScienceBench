"""Typeset the complete exported shared conversations selected for Discussion.

Run from any directory with Python 3. Source snapshots and their hashes live in
review/discussion_candidates. Message payloads are preserved literally; only
TeX escaping and discretionary line breaks are added. No private logs are read.
"""
from pathlib import Path
import hashlib
import json
import re

PAPER = Path(__file__).resolve().parents[1]
ARCHIVE = PAPER / "review/discussion_candidates"
CASES = [
    ("C2", "candidate_155", "Workflow Revision: BixBench with Persona 155", "app:case-workflow"),
    ("C1", "candidate_155", "Incremental Clarification: SciConvBench with Persona 155", "app:case-clarification"),
    ("C1", "persona_off", "Matched SciConvBench Conversation without a Persona", "app:case-clarification-off"),
]
ESCAPES = {"\\": r"\textbackslash{}", "{": r"\{", "}": r"\}",
           "$": r"\$", "&": r"\&", "#": r"\#", "%": r"\%",
           "_": r"\_", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
           "₀": r"\ensuremath{{}_0}"}


def escape(text):
    # Explicit CJK breaks also work in Tectonic builds without ICU locale data.
    closing = set("，。；：！？、）》】」』％,.!?;:)]}")
    result = []
    for i, c in enumerate(text):
        can_break = c in "/_=-" or "\u3400" <= c <= "\u9fff" or c in "，。；：！？、"
        if i + 1 < len(text) and text[i + 1] in closing:
            can_break = False
        result.append(ESCAPES.get(c, c) + (r"\allowbreak{}" if can_break else ""))
    return "".join(result)


def main():
    manifest = json.loads((ARCHIVE / "manifest.json").read_text())
    out = [r"""% Generated by scripts/build_interaction_cases.py; do not edit payloads.
\section{Full Interactions for the Discussion Cases}
\label{app:discussion-interactions}
This section reproduces the complete exported shared conversations behind
Figure~\ref{fig:discussion-cases}, including every recorded message and
handoff field. C2 documents workflow revision; C1 documents clarification
with persona 155 and its matched no-persona interaction. All are original
trial-1 endpoints using GPT-6 Astra with low reasoning, and each received
a normalized score of 100/100. Persona 155's full configured profile
appears in Appendix~\ref{app:persona-profile}.

The original Chinese and English wording is retained without abridgment.
Payload formatting, mathematical source notation and structured fields are
printed literally; line wrapping is adjusted for the page. The translated
main-text excerpts use editorial highlights and omission marks. Source
event numbers are preserved, including gaps corresponding to activity
outside the shared conversation. Private tool logs, system prompts and
evaluator material are outside this export. Source paths, event-log hashes
and byte-identical conversation snapshots are retained in the paper's
\texttt{review/discussion\_candidates} archive.

The workflow transcript refers to limma~\cite{ritchie2015limma},
Benjamini--Hochberg (BH) correction~\cite{benjamini1995fdr}, and
Holm correction~\cite{holm1979sequential}.

% The bundled OFL font is a renamed, character-subsetted Noto Sans CJK SC.
% XeLaTeX/Tectonic is required for original-language conversation text.
\font\interactionfont="[fonts/PSBTraceCJK.otf]" at 8.5pt
\newenvironment{interactionevent}[1]{%
  \begin{tcolorbox}[breakable,colback=gray!2,colframe=gray!45,
    boxrule=0.4pt,arc=1pt,left=7pt,right=7pt,top=4pt,bottom=4pt,
    before skip=5pt,after skip=5pt,lines before break=4,
    title={#1},title after break={#1 (continued)},
    colbacktitle=gray!12,coltitle=black,fonttitle=\small\bfseries]
  \interactionfont\baselineskip=11.5pt
  \raggedright
  \parindent=0pt\parskip=1.5pt\emergencystretch=1em
}{\end{tcolorbox}}
\newcommand{\interactionfield}[1]{\par{\normalfont\small\bfseries #1}\par\nobreak}
"""]
    verification = []
    for cid, persona, title, label in CASES:
        case = next(c for c in manifest["cases"] if c["id"] == cid)
        record = next(t for t in case["trajectories"] if t["persona"] == persona)
        source = ARCHIVE / record["snapshot"]
        raw = source.read_bytes()
        assert hashlib.sha256(raw).hexdigest() == record["shared_trajectory_sha256"]
        shared = raw.decode().split("## Shared conversation\n", 1)[1].split("## Provenance", 1)[0]
        out += [r"\Needspace{10\baselineskip}",
                r"\subsection{" + title + "}", r"\label{" + label + "}",
                r"Task: \texttt{" + escape(record["index_record"]["task_id"]) + "}. "
                + "Trial 1; original endpoint; persona " + escape(persona.replace("candidate_", "")) + ".",
                "% Snapshot SHA256: " + record["shared_trajectory_sha256"]]
        event_ids, fields = [], []
        for event in re.finditer(r"### Event (\d+) — ([^\n]+)\n(.*?)(?=### Event|\Z)", shared, re.S):
            event_ids.append(int(event[1]))
            role = event[2].replace("Simulator", "Researcher (simulator)")
            out.append(r"\begin{interactionevent}{Event " + event[1] + ": " + escape(role) + "}")
            for field in re.finditer(r"\*\*([^\n]+)\*\*\s+````text\n(.*?)\n````", event[3], re.S):
                out.append(r"\interactionfield{" + escape(field[1]) + "}")
                for line in field[2].splitlines():
                    out.append(escape(line) + r"\par" if line else r"\smallskip")
                fields.append({"event": int(event[1]), "field": field[1],
                               "payload_sha256": hashlib.sha256(field[2].encode()).hexdigest()})
            out.append(r"\end{interactionevent}")
        assert len(fields) == shared.count("````text\n"), "An exported field was lost"
        verification.append({"case": cid, "persona": persona, "snapshot": record["snapshot"],
                             "events": event_ids, "fields": fields})
    (PAPER / "sections/interaction_cases.tex").write_text("\n".join(out) + "\n")
    (ARCHIVE / "appendix_export.json").write_text(json.dumps(verification, indent=2) + "\n")
    print("Exported", sum(len(v["events"]) for v in verification), "events and",
          sum(len(v["fields"]) for v in verification), "complete fields from", len(CASES), "trajectories.")


if __name__ == "__main__":
    main()
